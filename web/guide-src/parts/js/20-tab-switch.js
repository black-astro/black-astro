function tabDrop(force){
  const tb = $("#tabbar");
  const open = force !== undefined ? force : !tb.classList.contains("open");
  tb.classList.toggle("open", open);
  $("#tabcur").setAttribute("aria-expanded", open ? "true" : "false");
}
